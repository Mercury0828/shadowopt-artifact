"""Workload families (seeded generators of batch sequences). Phase 0 uses W1, W2, W3 (D1/D2) and W1, W4, W6 (D4).

A query is (term indices into the family's term universe, coefficients, eps, delta). A batch is a list of queries
fixed before any answer is returned and independently of all returned answers (the generator never sees outcomes).
"""
from dataclasses import dataclass, field
from itertools import combinations

import numpy as np

from .store import TermBatch, terms_from_pairs


@dataclass
class Query:
    terms: np.ndarray  # indices into the universe
    coeffs: np.ndarray
    eps: float
    delta: float = 0.05
    const: float = 0.0
    name: str = ""


@dataclass
class Family:
    name: str
    universe: TermBatch
    batches: list  # list of list[Query]
    info: dict = field(default_factory=dict)

    def batch_terms(self, tau):
        idx = sorted(set(int(i) for q in self.batches[tau] for i in q.terms))
        return np.array(idx, np.int64)


# ----------------------------------------------------------------------------------------------------------------------
def w1_energy(terms, const, eps_seq=(0.1, 0.05, 0.03, 0.02, 0.015, 0.01), delta=0.05):
    """W1: the energy of a molecular Hamiltonian, re-asked at tightening targets (one query per batch)."""
    allidx = np.arange(terms.T)
    batches = [[Query(allidx, terms.coeff.copy(), eps, delta, const, f"E@{eps}")] for eps in eps_seq]
    return Family("W1", terms, batches, {"eps_seq": list(eps_seq)})


def w2_correlators(n, eps=0.05, delta=0.05, n_batches=6):
    """W2: all-pairs two-point correlators <s_i^a s_j^a>, a in {X,Y,Z}; each query one term; every batch asks all."""
    pairs = []
    for a in range(3):
        for i, j in combinations(range(n), 2):
            pairs.append([(i, a), (j, a)])
    U = terms_from_pairs(n, pairs)
    batch = [Query(np.array([t]), np.array([1.0]), eps, delta, 0.0, f"C{t}") for t in range(U.T)]
    return Family("W2", U, [list(batch) for _ in range(n_batches)], {"eps": eps})


def ghz_stabilizer_group(s):
    """All 2^s elements of GHZ_s's stabilizer group as (pairs, sign): generated by X^{(s)} and Z_i Z_{i+1}.
    Element = X^{(s)a} * Z^{z}, z of even weight; with Y = i X Z: X Z = -i Y on a qubit."""
    out = []
    for a in (0, 1):
        for zmask in range(2 ** s):
            if bin(zmask).count("1") % 2:
                continue
            pairs = []
            phase = 1 + 0j
            for q in range(s):
                zq = (zmask >> q) & 1
                if a and zq:
                    pairs.append((q, 1))
                    phase *= -1j  # X Z = -i Y
                elif a:
                    pairs.append((q, 0))
                elif zq:
                    pairs.append((q, 2))
            assert abs(phase.imag) < 1e-12 or abs(phase.real) < 1e-12
            out.append((pairs, phase))
    return out


def w3_local_fidelities(n, windows=((4, 1), (8, 6)), eps=0.05, delta=0.05, n_batches=6):
    """W3: fidelities of contiguous windows to GHZ_s targets, F = 2^-s sum_g <g>. Windows given as (s, stride).
    Each query = one window fidelity (2^s - 1 non-identity terms + constant 2^-s)."""
    grp = {}
    for s, _ in windows:
        grp[s] = ghz_stabilizer_group(s)
    key2idx = {}
    pairs_list = []
    queries = []
    for s, stride in windows:
        for w0 in range(0, n - s + 1, stride):
            tids, cs = [], []
            for pairs, phase in grp[s]:
                if not pairs:
                    continue
                if abs(phase.imag) > 1e-12:
                    raise AssertionError("non-Hermitian element")
                key = tuple((w0 + q, b) for q, b in pairs)
                if key not in key2idx:
                    key2idx[key] = len(pairs_list)
                    pairs_list.append(list(key))
                tids.append(key2idx[key])
                cs.append(phase.real / 2 ** s)
            queries.append(Query(np.array(tids), np.array(cs), eps, delta, 1.0 / 2 ** s, f"F{s}@{w0}"))
    U = terms_from_pairs(n, pairs_list)
    return Family("W3", U, [list(queries) for _ in range(n_batches)], {"windows": [list(w) for w in windows]})


def w4_zipf(n, seed, universe_size=400, n_batches=20, batch_size=40, alpha=1.1, kmax=6, eps=0.05, delta=0.05):
    """W4: Zipf mixture of k-local terms (k <= kmax) recurring across batches. Supports: k distinct qubits inside a
    random window of width 2k; bases uniform. Each query = one term."""
    rng = np.random.default_rng(seed)
    pairs, seen = [], set()
    while len(pairs) < universe_size:
        k = int(rng.integers(1, kmax + 1))
        w0 = int(rng.integers(0, max(1, n - 2 * k + 1)))
        qs = sorted(rng.choice(np.arange(w0, min(n, w0 + 2 * k)), size=k, replace=False).tolist())
        bs = rng.integers(0, 3, size=k).tolist()
        key = tuple(zip(qs, bs))
        if key in seen:
            continue
        seen.add(key)
        pairs.append(list(key))
    U = terms_from_pairs(n, pairs)
    perm = rng.permutation(universe_size)
    p = 1.0 / np.arange(1, universe_size + 1) ** alpha
    p /= p.sum()
    batches = []
    for _ in range(n_batches):
        ranks = rng.choice(universe_size, size=batch_size, replace=True, p=p)
        ids = sorted(set(perm[ranks].tolist()))
        batches.append([Query(np.array([i]), np.array([1.0]), eps, delta, 0.0, f"T{i}") for i in ids])
    return Family("W4", U, batches, {"seed": seed, "alpha": alpha})


def w6_heavytail(n, seed, n_light=300, n_heavy=4, kmin_heavy=8, kmax_heavy=10, n_batches=12, batch_light=30,
                 eps=0.05, delta=0.05, heavy_every=3):
    """W6: many low-weight terms (k <= 4, Zipf over a universe) plus a few heavy terms (k in [8, 10]) asked every
    `heavy_every` batches. Each query one term with coefficient 1."""
    rng = np.random.default_rng(seed)
    pairs, seen = [], set()
    while len(pairs) < n_light:
        k = int(rng.integers(1, 5))
        w0 = int(rng.integers(0, max(1, n - 2 * k + 1)))
        qs = sorted(rng.choice(np.arange(w0, min(n, w0 + 2 * k)), size=k, replace=False).tolist())
        key = tuple(zip(qs, rng.integers(0, 3, size=k).tolist()))
        if key not in seen:
            seen.add(key)
            pairs.append(list(key))
    heavy = []
    while len(heavy) < n_heavy:
        k = int(rng.integers(kmin_heavy, kmax_heavy + 1))
        qs = sorted(rng.choice(n, size=k, replace=False).tolist())
        key = tuple(zip(qs, rng.integers(0, 3, size=k).tolist()))
        if key not in seen:
            seen.add(key)
            heavy.append(list(key))
    U = terms_from_pairs(n, pairs + heavy)
    p = 1.0 / np.arange(1, n_light + 1) ** 1.1
    p /= p.sum()
    batches = []
    for tau in range(n_batches):
        ids = sorted(set(rng.choice(n_light, size=batch_light, replace=True, p=p).tolist()))
        qs = [Query(np.array([i]), np.array([1.0]), eps, delta, 0.0, f"L{i}") for i in ids]
        if tau % heavy_every == heavy_every - 1:
            qs += [Query(np.array([n_light + h]), np.array([1.0]), eps, delta, 0.0, f"H{h}") for h in range(n_heavy)]
        batches.append(qs)
    return Family("W6", U, batches, {"seed": seed})


def w5_drift(n, seed, n_phases=4, phase_len=5, phase_universe=120, batch_size=40, alpha=1.1, kmax=6, eps=0.05,
             delta=0.05):
    """W5 (registered 2026-11-08, PREREG A11, before any W5 number): a drifting mixture — the term distribution changes
    every `phase_len` batches. Each phase has its own random universe of `phase_universe` k-local terms (k ~ U{1..kmax},
    support inside a random window of width 2k, uniform bases; drawn like W4) and its own Zipf(alpha) popularity over a
    fresh random permutation; batches draw `batch_size` terms with replacement from the current phase. Single-term queries,
    fixed (eps, delta). Information contract: C0 (no catalogue; exploratory)."""
    rng = np.random.default_rng([seed, 5])
    pairs, seen, phase_of = [], {}, []
    phase_ids = []
    for ph in range(n_phases):
        ids = []
        while len(ids) < phase_universe:
            k = int(rng.integers(1, kmax + 1))
            w0 = int(rng.integers(0, max(1, n - 2 * k + 1)))
            qs = sorted(rng.choice(np.arange(w0, min(n, w0 + 2 * k)), size=k, replace=False).tolist())
            key = tuple(zip(qs, rng.integers(0, 3, size=k).tolist()))
            if key in seen:
                if seen[key] not in ids:
                    ids.append(seen[key])
                continue
            seen[key] = len(pairs)
            pairs.append(list(key))
            ids.append(seen[key])
        phase_ids.append(ids)
    U = terms_from_pairs(n, pairs)
    p = 1.0 / np.arange(1, phase_universe + 1) ** alpha
    p /= p.sum()
    batches = []
    for ph in range(n_phases):
        perm = rng.permutation(phase_universe)
        for _ in range(phase_len):
            ranks = rng.choice(phase_universe, size=batch_size, replace=True, p=p)
            ids = sorted(set(phase_ids[ph][perm[r]] for r in ranks))
            batches.append([Query(np.array([i]), np.array([1.0]), eps, delta, 0.0, f"T{i}") for i in ids])
    return Family("W5", U, batches, {"seed": seed, "phases": n_phases, "phase_len": phase_len})


def w3_cluster_fidelities(n, windows=((4, 1), (8, 6)), eps=0.05, delta=0.05, n_batches=6):
    """W3 on the TEST cluster state: fidelities of contiguous windows to the open-boundary cluster
    state of the window, F = 2^-s sum_{g in G_w} <g>, G_w generated by the window-truncated generators Z_{i-1} X_i Z_{i+1}
    (Z factors outside the window dropped). Same windows and targets as the DEV W3 (GHZ)."""
    import stim
    key2idx, pairs_list, queries = {}, [], []
    for s, stride in windows:
        gens = []
        for i in range(s):
            p = ["_"] * s
            p[i] = "X"
            if i > 0:
                p[i - 1] = "Z"
            if i < s - 1:
                p[i + 1] = "Z"
            gens.append(stim.PauliString("".join(p)))
        elems = []
        for mask in range(1, 2 ** s):
            g = stim.PauliString(s)
            for i in range(s):
                if (mask >> i) & 1:
                    g = g * gens[i]
            assert g.sign in (1, -1)
            elems.append(g)
        for w0 in range(0, n - s + 1, stride):
            tids, cs = [], []
            for g in elems:
                key = tuple((w0 + q, "XYZ".index("_XYZ"[g[q]])) for q in range(s) if g[q] != 0)
                if key not in key2idx:
                    key2idx[key] = len(pairs_list)
                    pairs_list.append(list(key))
                tids.append(key2idx[key])
                cs.append(float(np.real(g.sign)) / 2 ** s)
            queries.append(Query(np.array(tids), np.array(cs), eps, delta, 1.0 / 2 ** s, f"C{s}@{w0}"))
    U = terms_from_pairs(n, pairs_list)
    return Family("W3", U, [list(queries) for _ in range(n_batches)], {"windows": [list(w) for w in windows],
                                                                       "target": "window cluster state"})
